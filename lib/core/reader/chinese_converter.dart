/// 阅读正文的中文简繁转换模式（对标 Legado ReadStyleDialog 的
/// chineseConverter：TransType 简转繁/繁转简）。
///
/// 转换是字符级（含少量短语消歧），且每个字替换前后长度恒定——
/// 因此转换不会改变正文的字符偏移，native 路径批注/书签/朗读偏移保持稳定。
enum ChineseConversionMode {
  /// 不转换，显示原文。
  off,

  /// 简体 → 繁体。
  simplifiedToTraditional,

  /// 繁体 → 简体。
  traditionalToSimplified;

  static ChineseConversionMode fromName(String? name) => values.firstWhere(
    (mode) => mode.name == name,
    orElse: () => ChineseConversionMode.off,
  );
}

