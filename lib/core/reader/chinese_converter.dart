  static String convert(String text, ChineseConversionMode mode) {
    if (text.isEmpty || mode == ChineseConversionMode.off) return text;
    return mode == ChineseConversionMode.simplifiedToTraditional
        ? _simplifiedToTraditional(text)
        : _traditionalToSimplified(text);
  }

  static String _simplifiedToTraditional(String text) {
    final result = StringBuffer();
    var index = 0;
    while (index < text.length) {
      // 优先匹配最长短语，处理一简多繁（如「头发」→「頭髮」）。
      var matched = false;
      for (final phrase in _s2tPhrases) {
        if (text.startsWith(phrase.key, index)) {
          result.write(phrase.value);
          index += phrase.key.length;
          matched = true;
          break;
        }
      }
      if (matched) continue;
      final char = text[index];
      result.write(_s2t[char] ?? char);
      index += 1;
    }
    return result.toString();
  }

  static String _traditionalToSimplified(String text) {
    final map = _t2s;
    final result = StringBuffer();
    for (final char in text.split('')) {
      result.write(map[char] ?? char);
    }
    return result.toString();
  }

